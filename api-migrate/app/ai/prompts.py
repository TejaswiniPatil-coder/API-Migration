"""
Prompt Templates — structured prompts for AI-assisted migration.

Each prompt provides the AI with:
  - source context
  - old / new API signatures
  - migration rules and constraints
  - validation requirements

The AI is expected to return structured JSON.
"""

from __future__ import annotations

from typing import Optional
from app.models.api_models import DetectedAPI
from app.models.migration_models import MigrationMapping, MigrationPlan


SYSTEM_PROMPT = """\
You are an expert Python API migration assistant.

Your role is to help migrate deprecated API calls to their newer equivalents.
You receive structured information about the migration and must return a JSON response.

Rules:
1. Always return valid JSON matching the required schema.
2. Explain your reasoning clearly.
3. List any assumptions you make.
4. If you are uncertain, say so — do not guess.
5. Never invent APIs that are not in the provided specification.
6. The deterministic AST pipeline handles the actual code transformation.
   Your role is to assist with complex cases, provide explanations, and
   suggest validation strategies.
"""

MIGRATION_ASSIST_TEMPLATE = """\
## Migration Task

### Source Context
```python
{source_code}
```

### Deprecated API Detected
- **API**: `{old_api}`
- **Line**: {line}
- **Arguments**: {arguments}

### Migration Rule
- **Old API**: `{old_api}` (version {old_version})
- **New API**: `{new_api}` (version {new_version})
- **Transformation Type**: {transformation_type}
- **Description**: {description}

### Old Signature
{old_signature}

### New Signature
{new_signature}

### Argument Transformations
{arg_transformations}

### Semantic Analysis Notes
{semantic_notes}

## Required JSON Response
Return a JSON object with these fields:
{{
  "success": true/false,
  "explanation": "Clear explanation of the migration",
  "assumptions": ["list of assumptions made"],
  "suggestions": ["list of validation suggestions"],
  "confidence": 0.0 to 1.0,
  "complex_notes": "any notes about edge cases or risks"
}}
"""


def build_migration_prompt(
    source_code: str,
    detection: DetectedAPI,
    mapping: MigrationMapping,
    plan: MigrationPlan,
    semantic_notes: Optional[list[str]] = None,
) -> str:
    """Build a structured prompt for AI migration assistance.

    Parameters
    ----------
    source_code : str
        The original source code.
    detection : DetectedAPI
        The detected deprecated API call.
    mapping : MigrationMapping
        The migration rule being applied.
    plan : MigrationPlan
        The migration plan generated by the planner.
    semantic_notes : list[str], optional
        Notes from semantic analysis.

    Returns
    -------
    str
        Formatted prompt string.
    """
    args_str = ", ".join(detection.arguments) if detection.arguments else "(none)"
    old_sig_str = ", ".join(mapping.old_signature) if mapping.old_signature else "(no parameters)"
    new_sig_str = ", ".join(mapping.new_signature) if mapping.new_signature else "(no parameters)"

    arg_txn_lines = []
    for txn in mapping.argument_transformations:
        old_name = txn.get("old_name", "—")
        new_name = txn.get("new_name", "—")
        conv = txn.get("type_conversion", "none")
        arg_txn_lines.append(f"  - {old_name} → {new_name} (conversion: {conv})")
    arg_txn_str = "\n".join(arg_txn_lines) if arg_txn_lines else "  (no argument transformations)"

    sem_notes_str = "\n".join(f"  - {n}" for n in (semantic_notes or [])) or "  (none)"

    return MIGRATION_ASSIST_TEMPLATE.format(
        source_code=source_code,
        old_api=mapping.old_api,
        new_api=mapping.new_api,
        line=detection.line,
        arguments=args_str,
        old_version=mapping.old_version,
        new_version=mapping.new_version,
        transformation_type=mapping.transformation_type,
        description=mapping.description,
        old_signature=old_sig_str,
        new_signature=new_sig_str,
        arg_transformations=arg_txn_str,
        semantic_notes=sem_notes_str,
    )
